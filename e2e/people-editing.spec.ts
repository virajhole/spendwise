import { test, expect } from "@playwright/test";
import { waitForApp } from "./helpers";

test("chat debts can be corrected and filtered by direction and date", async ({ page }) => {
  await waitForApp(page);
  await page.getByLabel("Quick expense").fill("mujhe Rini ko 299 dene hain");
  await page.getByRole("button", { name: "Send expense" }).click();
  await expect(page.getByLabel("Quick expense")).toHaveValue("");
  await page.getByRole("navigation").getByRole("link", { name: "People", exact: true }).click();
  await page.getByRole("button", { name: "Entries", exact: true }).click();
  await page.getByRole("button", { name: /You owe.*View payables/ }).click();
  const card = page.locator("article");
  await expect(card).toHaveCount(1);
  await expect(card).toContainText("₹299");
  await page.getByRole("button", { name: "Edit Rini", exact: true }).click();
  const sheet = page.getByRole("dialog");
  await sheet.getByLabel("Person's name").fill("Riya");
  await sheet.getByLabel(/Amount/).fill("399");
  await sheet.getByLabel("Entry type").selectOption("lent");
  await sheet.getByLabel("Date", { exact: true }).fill("2026-09-01");
  await sheet.getByRole("button", { name: "Save changes" }).click();
  await expect(sheet).toBeHidden();
  await expect(card).toHaveCount(0);
  await page.getByRole("button", { name: /You'll get.*View receivables/ }).click();
  await expect(card).toContainText("Riya");
  await expect(card).toContainText("₹399");
  await expect(card).toContainText("2026-09-01");
  await page.getByLabel("From date").fill("2026-10-01");
  await expect(card).toHaveCount(0);
  await page.getByLabel("From date").fill("2026-09-01");
  await expect(card).toHaveCount(1);
  await page.reload();
  await page.getByRole("button", { name: "Entries", exact: true }).click();
  await expect(page.locator("article")).toContainText("Riya");
});

test("fixed shares divide only the remainder and remain editable after repayment", async ({ page }) => {
  await waitForApp(page);
  await page.getByRole("navigation").getByRole("link", { name: "People", exact: true }).click();
  await page.getByRole("button", { name: "Entries", exact: true }).click();
  await page.getByRole("button", { name: "Split a bill", exact: true }).click();
  const sheet = page.getByRole("dialog");
  await sheet.getByLabel(/Bill total/).fill("1000");
  await sheet.getByLabel(/Friends \(/).fill("Viraj, Kishon, Rini, Arbaz");
  await sheet.getByRole("button", { name: "Fixed + rest" }).click();
  await sheet.getByLabel("Me share").fill("0");
  await sheet.getByLabel("Viraj share").fill("200");
  await sheet.getByLabel("Kishon share").fill("200");
  await sheet.getByRole("button", { name: "Save split" }).click();
  await expect(sheet).toBeHidden();
  const viraj = page.locator("article").filter({ has: page.getByRole("heading", { name: "Viraj", exact: true }) });
  const rini = page.locator("article").filter({ has: page.getByRole("heading", { name: "Rini", exact: true }) });
  await expect(viraj).toContainText("₹200");
  await expect(rini).toContainText("₹300");
  await viraj.getByRole("button", { name: "Record payment" }).click();
  await sheet.getByLabel(/Amount/).fill("50");
  await sheet.getByRole("button", { name: "Record payment" }).click();
  await expect(sheet).toBeHidden();
  await viraj.getByRole("button", { name: "Edit Viraj" }).click();
  await sheet.getByLabel("Friend 1 name").fill("Viraj Shah");
  await sheet.getByRole("button", { name: "Save changes" }).click();
  await expect(sheet).toBeHidden();
  const edited = page.locator("article").filter({ has: page.getByRole("heading", { name: "Viraj Shah", exact: true }) });
  await expect(edited).toContainText("₹150");
  await expect(edited).toContainText("Paid ₹50");
  await page.setViewportSize({ width: 320, height: 780 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("recurring schedules can be edited and paused; currency setting is removed", async ({ page }) => {
  await waitForApp(page);
  await page.getByRole("navigation").getByRole("link", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("region", { name: "Currency", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Add recurring expense", exact: true }).click();
  const sheet = page.getByRole("dialog");
  await sheet.getByLabel("Recurring name").fill("Monthly rent");
  await sheet.getByLabel(/Recurring amount/).fill("1000");
  await sheet.getByLabel("Day of month").fill("28");
  await sheet.getByRole("button", { name: "Add schedule" }).click();
  await expect(sheet).toBeHidden();
  await page.getByRole("button", { name: "Edit recurring Monthly rent" }).click();
  await sheet.getByLabel("Recurring name").fill("Home rent");
  await sheet.getByLabel(/Recurring amount/).fill("1500");
  await sheet.getByLabel("Day of month").fill("27");
  await sheet.getByLabel("Active schedule").uncheck();
  await sheet.getByRole("button", { name: "Save changes" }).click();
  await expect(sheet).toBeHidden();
  const recurring = page.getByRole("region", { name: "Recurring expenses", exact: true });
  await expect(recurring).toContainText("Home rent");
  await expect(recurring).toContainText("₹1,500");
  await expect(recurring).toContainText("Day 27 monthly");
  await expect(page.getByRole("button", { name: "Toggle Home rent" })).toHaveText("Paused · Resume");
  await page.reload();
  await expect(recurring).toContainText("Home rent");
});
